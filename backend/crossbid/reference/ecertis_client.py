"""eCertis access, split in two halves that never mix.

**Build time** -- `EcertisRestClient` talks to the live service. Only
`scripts/build_ecertis_cache.py` uses it, and only a maintainer runs that.

**Run time** -- `load_criteria`, `load_evidence` and `find_evidence` read the JSON
committed under `data/ecertis/`. They open no socket, so the graph, the tools and the
tests all work with the network unplugged. That is the whole point of the cache
(docs/project-plan.md, "reference/data/ is generated by a script and committed").

Also here, because both halves need the same answer: the canonical JSON encoding and the
content hash that make the cache byte-stable across re-runs.

The service model is criterion-centric and three levels deep, which the endpoints hide:

    GET criteria                          -> 56 EU-level ESPD criteria (the enum source)
    GET criteria?nationalEntity=de        -> the same 56, but as DE-scoped *sub*-criteria
                                             with different UUIDs -- not EU-wide ids
    GET criteria/{eu_uuid}?countryFilter=de
        -> the EU criterion, its DE SubCriterion[] (national law references), each with
           RequirementGroup[] -> TypeOfEvidence[]: the actual German papers

So the only identifier that means the same thing in Paris and in Berlin is the EU-level
UUID from the bare `criteria` call. Everything is keyed on that.
"""

from __future__ import annotations

import hashlib
import json
import time
from collections.abc import Callable, Mapping, Sequence
from functools import lru_cache
from pathlib import Path
from types import MappingProxyType, TracebackType
from typing import Any, Final

import httpx
from pydantic import ValidationError

from crossbid.reference.ecertis_schema import (
    CachedCriterion,
    CachedCriterionEvidence,
    CachedEvidence,
    CachedLegislation,
    CachedSubCriterion,
    CriteriaCache,
    EvidenceCache,
    WireCriteriaList,
    WireCriterionDetail,
    WireEvidence,
    WireLegislation,
    WireSubCriterion,
    WireText,
)

ECERTIS_BASE_URL: Final = "https://ec.europa.eu/growth/tools-databases/ecertisrest/"
DATA_DIR: Final = Path(__file__).resolve().parent / "data" / "ecertis"
CRITERIA_FILENAME: Final = "criteria.json"
EVIDENCE_FILENAME_TEMPLATE: Final = "evidence_{country}.json"

REQUEST_TIMEOUT_S: Final = 60.0
MAX_ATTEMPTS: Final = 3
RETRY_BACKOFF_S: Final = 2.0
"""Sleeps 2s then 4s before giving up on a request.

Measured on 2026-09-10: eCertis answers `200` with an empty body in two different
situations. For 18 of the 112 country/criterion pairs the emptiness is *stable* -- six
consecutive calls, zero bytes every time -- and means the country registered no national
sub-criterion for that EU criterion. Occasionally a pair that normally answers returns
empty once and then answers on the retry. Retrying cannot tell the two apart, so the
caller records a persistent empty as "no evidence" and the build script guards against
losing evidence the committed file already had.
"""
TAXONOMY_NATIONAL_ENTITY: Final = "eu"
"""Where the ESPD taxonomy label comes from.

`GET criteria` returns `CriteriaTypeID` but no `CriteriaTypeName`, so the bare listing
cannot say whether a criterion is an exclusion ground or a selection criterion. Every
`nationalEntity` listing does carry the label, and the labels are identical across
entities (checked de vs fr on 2026-09-10: 56/56 the same eight strings), so it is an
EU-level taxonomy that the bare endpoint simply forgets to send. Taken from the `eu`
entity so the criterion list does not depend on which countries are being built, and
matched on the criterion name because the entity's own UUIDs are country-scoped.
"""

RESPONSE_LANGUAGE: Final = "en"
"""Pinned, not left to the server default, so the cache cannot shift under us.

`lang=de` is also accepted and returns machine-translated German; it is not cached here
because v1's UI language is English and S1.1.2 has not asked for it yet.
"""

JSON_INDENT: Final = 2
HASH_EXCLUDED_HEADER_FIELDS: Final = frozenset({"source_date", "content_sha256"})


class EcertisCacheError(RuntimeError):
    """The committed cache is missing, unreadable, or has been hand-edited."""


class EcertisUnavailableError(RuntimeError):
    """The live service did not answer usefully. Build time only -- never at run time."""


# --------------------------------------------------------------------- canonical form


def canonical_json(payload: Mapping[str, Any]) -> str:
    """Encode exactly one way: sorted keys, fixed indent, real UTF-8, trailing newline.

    Every source of byte-level drift between two runs is nailed down here. List order is
    not -- callers sort their own lists before handing the payload over.
    """
    body = json.dumps(payload, ensure_ascii=False, indent=JSON_INDENT, sort_keys=True)
    return f"{body}\n"


def content_hash(payload: Mapping[str, Any]) -> str:
    """SHA-256 over the canonical form of everything except the provenance fields.

    `source_date` is excluded because it is *derived* from this hash: it only advances
    when the hash changes. Including it would make the hash change every day.
    """
    body = {k: v for k, v in payload.items() if k not in HASH_EXCLUDED_HEADER_FIELDS}
    return hashlib.sha256(canonical_json(body).encode("utf-8")).hexdigest()


# ------------------------------------------------------------------------ normalising


def _text(field: WireText | None) -> str:
    """One eCertis scalar as a clean string. Whitespace is collapsed, absent becomes ""."""
    if field is None or field.value is None:
        return ""
    return " ".join(field.value.split())


def _stable_text(field: Sequence[WireText] | WireText | None) -> str:
    """One string out of a field eCertis sends as an object *or* as a list.

    When it is a list, the lexicographically smallest non-empty value wins rather than the
    first one. eCertis does not promise a list order, and "whatever arrived first" would
    make the committed cache depend on it -- the one thing S1.1.1 must not do. Every such
    list observed on 2026-09-10 held a single value, so this changes no current output.
    """
    if field is None:
        return ""
    if isinstance(field, WireText):
        return _text(field)
    return min((text for item in field if (text := _text(item))), default="")


def _legislation(refs: Sequence[WireLegislation]) -> tuple[CachedLegislation, ...]:
    rows = [
        CachedLegislation(
            title=_text(ref.title),
            description=_text(ref.description),
            jurisdiction=_text(ref.jurisdiction_level_code),
            article=_text(ref.article),
            uri=_text(ref.uri),
        )
        for ref in refs
    ]
    return tuple(sorted(rows, key=lambda r: (r.title, r.article, r.uri, r.description)))


def _issuers(evidence: WireEvidence) -> tuple[str, ...]:
    names = {
        _text(party_name.name)
        for party in evidence.issuer_party
        for party_name in party.party_name
        if _text(party_name.name)
    }
    return tuple(sorted(names))


def _jurisdictions(evidence: WireEvidence) -> tuple[str, ...]:
    codes = {_text(code) for code in evidence.jurisdiction_level_code}
    return tuple(sorted(code for code in codes if code))


def _intended_use(evidence: WireEvidence) -> str:
    use = evidence.intended_use
    return _stable_text(use.description) if use else ""


def _detail_url(evidence: WireEvidence) -> str:
    """The eCertis web page for the document. Smallest wins, for the `_stable_text` reason."""
    candidates = (
        _text(ref.attachment.external_reference.uri)
        for ref in evidence.document_reference
        if ref.attachment and ref.attachment.external_reference
    )
    return min((uri for uri in candidates if uri), default="")


def _validity_period(evidence: WireEvidence) -> str:
    candidates = (
        _stable_text(ref.validity_period.description)
        for ref in evidence.document_reference
        if ref.validity_period
    )
    return min((text for text in candidates if text), default="")


def _evidence_row(evidence_id: str, wire: WireEvidence) -> CachedEvidence:
    """One `TypeOfEvidence` occurrence as a cache row. `groups` is filled in by the caller."""
    return CachedEvidence(
        id=evidence_id,
        type_code=_text(wire.type_code),
        name=_text(wire.name),
        description=_text(wire.description),
        issuers=_issuers(wire),
        addressee=_text(wire.addressee_description),
        jurisdictions=_jurisdictions(wire),
        validity_period=_validity_period(wire),
        intended_use=_intended_use(wire),
        detail_url=_detail_url(wire),
        groups=(),
    )


def _merge_evidence(rows: Sequence[CachedEvidence], groups: tuple[str, ...]) -> CachedEvidence:
    """Fold every occurrence of one document id into a single row, order-independently.

    53 of the cached evidences (49 DE, 4 FR on 2026-09-10) are referenced from more than
    one `RequirementGroup`. Today every such pair is byte-identical, so simply keeping the
    first occurrence would give the same answer -- but only because eCertis happens to
    repeat itself, which it does not promise. Merging instead: sets are unioned, and a
    scalar takes the smallest non-empty value, so a stub occurrence cannot erase a
    populated one and the result cannot depend on which group was walked first.
    """

    def smallest(pick: Callable[[CachedEvidence], str]) -> str:
        return min((value for row in rows if (value := pick(row))), default="")

    def union(pick: Callable[[CachedEvidence], tuple[str, ...]]) -> tuple[str, ...]:
        return tuple(sorted({value for row in rows for value in pick(row)}))

    return CachedEvidence(
        id=rows[0].id,
        type_code=smallest(lambda row: row.type_code),
        name=smallest(lambda row: row.name),
        description=smallest(lambda row: row.description),
        issuers=union(lambda row: row.issuers),
        addressee=smallest(lambda row: row.addressee),
        jurisdictions=union(lambda row: row.jurisdictions),
        validity_period=smallest(lambda row: row.validity_period),
        intended_use=smallest(lambda row: row.intended_use),
        detail_url=smallest(lambda row: row.detail_url),
        groups=groups,
    )


def _evidences(sub: WireSubCriterion) -> tuple[CachedEvidence, ...]:
    """Flatten `RequirementGroup[] -> TypeOfEvidence[]`, keeping the group ids as a hint.

    Groups are *alternatives* ("submit any one of these"), so the cache row is the
    document, not the alternative: a document referenced from several groups appears once
    with every group id recorded. See `_merge_evidence` for why that is a merge rather
    than a first-one-wins.
    """
    occurrences: dict[str, list[CachedEvidence]] = {}
    groups: dict[str, set[str]] = {}
    for group in sub.requirement_group:
        group_id = _text(group.id)
        for wire in group.type_of_evidence:
            evidence_id = _text(wire.id)
            if not evidence_id:
                continue
            occurrences.setdefault(evidence_id, []).append(_evidence_row(evidence_id, wire))
            groups.setdefault(evidence_id, set()).add(group_id)

    rows = [
        _merge_evidence(candidates, tuple(sorted(g for g in groups[evidence_id] if g)))
        for evidence_id, candidates in occurrences.items()
    ]
    return tuple(sorted(rows, key=lambda r: (r.name, r.id)))


def _sub_criteria(detail: WireCriterionDetail) -> tuple[CachedSubCriterion, ...]:
    rows = [
        CachedSubCriterion(
            id=_text(sub.id),
            name=_text(sub.name),
            description=_text(sub.description),
            legislation=_legislation(sub.legislation_reference),
            evidences=_evidences(sub),
        )
        for sub in detail.sub_criterion
        if _text(sub.id)
    ]
    return tuple(sorted(rows, key=lambda r: r.id))


# ---------------------------------------------------------------- build-time REST half


class EcertisRestClient:
    """Live eCertis, GET only, no key. Used by the build script and nothing else.

    Retries an empty body as hard as a network error: the service answers `200` with zero
    bytes now and then, and letting that through would silently shrink the cache.
    """

    def __init__(
        self,
        base_url: str = ECERTIS_BASE_URL,
        *,
        client: httpx.Client | None = None,
        max_attempts: int = MAX_ATTEMPTS,
    ) -> None:
        self._max_attempts = max_attempts
        self._owns_client = client is None
        self._client = client or httpx.Client(
            base_url=base_url,
            timeout=REQUEST_TIMEOUT_S,
            headers={"Accept": "application/json"},
            follow_redirects=True,
        )

    def __enter__(self) -> EcertisRestClient:
        return self

    def __exit__(
        self,
        exc_type: type[BaseException] | None,
        exc: BaseException | None,
        tb: TracebackType | None,
    ) -> None:
        self.close()

    def close(self) -> None:
        if self._owns_client:
            self._client.close()

    def fetch_criteria(self) -> tuple[CachedCriterion, ...]:
        """The EU-level criteria, with the taxonomy label stitched in from the `eu` entity.

        Raises if either listing comes back empty: unlike a single criterion in a single
        country, an empty criterion list is never a legitimate answer.
        """
        listing = self._fetch_listing(params={"lang": RESPONSE_LANGUAGE})
        taxonomy = self._fetch_taxonomy()
        rows = [
            CachedCriterion(
                id=_text(row.id),
                name=_text(row.name),
                description=_text(row.description),
                type_name=taxonomy.get(_text(row.name), ""),
                version=_text(row.version_id),
            )
            for row in listing.criterion
            if _text(row.id) and _text(row.name)
        ]
        if not rows:
            raise EcertisUnavailableError("GET criteria returned no usable criterion rows")
        return tuple(sorted(rows, key=lambda r: r.id))

    def _fetch_taxonomy(self) -> Mapping[str, str]:
        """Criterion name to ESPD taxonomy label. See `TAXONOMY_NATIONAL_ENTITY`."""
        listing = self._fetch_listing(
            params={"nationalEntity": TAXONOMY_NATIONAL_ENTITY, "lang": RESPONSE_LANGUAGE}
        )
        return {
            name: label
            for row in listing.criterion
            if (name := _text(row.name)) and (label := _text(row.criteria_type_name))
        }

    def _fetch_listing(self, params: Mapping[str, str]) -> WireCriteriaList:
        payload = self._get_json("criteria", params=params)
        if payload is None:
            raise EcertisUnavailableError(
                f"GET criteria {dict(params)} returned an empty body after retries"
            )
        try:
            return WireCriteriaList.model_validate(payload)
        except ValidationError as err:
            message = f"GET criteria {dict(params)} has an unexpected shape: {err}"
            raise EcertisUnavailableError(message) from err

    def fetch_evidence(
        self, criterion: CachedCriterion, country: str
    ) -> tuple[CachedCriterionEvidence, bool]:
        """Evidence for one criterion in one country.

        Returns the row plus whether the service actually answered. An empty body after
        every retry is reported as `False` rather than raised: the caller decides whether
        one silent criterion is tolerable or the whole country failed.
        """
        payload = self._get_json(
            f"criteria/{criterion.id}",
            params={"countryFilter": country, "lang": RESPONSE_LANGUAGE},
        )
        empty = CachedCriterionEvidence(
            criterion_id=criterion.id, criterion_name=criterion.name, sub_criteria=()
        )
        if payload is None:
            return empty, False
        try:
            detail = WireCriterionDetail.model_validate(payload)
        except ValidationError as err:
            raise EcertisUnavailableError(
                f"criteria/{criterion.id}?countryFilter={country} "
                f"has an unexpected shape: {err}"
            ) from err
        return empty.model_copy(update={"sub_criteria": _sub_criteria(detail)}), True

    def _get_json(self, path: str, params: Mapping[str, str]) -> dict[str, Any] | None:
        """GET with retries. `None` means "answered, but with nothing" -- not an error yet."""
        last_error: Exception | None = None
        for attempt in range(1, self._max_attempts + 1):
            try:
                response = self._client.get(path, params=dict(params))
                response.raise_for_status()
            except httpx.HTTPError as err:
                last_error = err
            else:
                if response.content.strip():
                    return self._decode(path, response)
                last_error = None
            if attempt < self._max_attempts:
                self._sleep(RETRY_BACKOFF_S * attempt)
        if last_error is not None:
            message = f"GET {path} failed after {self._max_attempts} attempts: {last_error}"
            raise EcertisUnavailableError(message) from last_error
        return None

    @staticmethod
    def _decode(path: str, response: httpx.Response) -> dict[str, Any]:
        try:
            payload = response.json()
        except ValueError as err:
            message = f"GET {path} returned malformed JSON: {err}"
            raise EcertisUnavailableError(message) from err
        if not isinstance(payload, dict):
            kind = type(payload).__name__
            raise EcertisUnavailableError(f"GET {path} returned {kind}, not an object")
        return payload

    @staticmethod
    def _sleep(seconds: float) -> None:
        """The only wall-clock wait in the module, isolated so tests can patch it away."""
        time.sleep(seconds)


# ------------------------------------------------------------- run-time cache-load half


def criteria_path() -> Path:
    return DATA_DIR / CRITERIA_FILENAME


def evidence_path(country: str) -> Path:
    return DATA_DIR / EVIDENCE_FILENAME_TEMPLATE.format(country=country.lower())


def _read_cache(path: Path) -> dict[str, Any]:
    if not path.is_file():
        raise EcertisCacheError(
            f"{path} is missing. Run `uv run python scripts/build_ecertis_cache.py`."
        )
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as err:
        raise EcertisCacheError(f"{path} could not be read: {err}") from err
    if not isinstance(payload, dict):
        raise EcertisCacheError(f"{path} is not a JSON object")
    expected = payload.get("content_sha256")
    actual = content_hash(payload)
    if expected != actual:
        raise EcertisCacheError(
            f"{path} has been hand-edited: content_sha256 is {expected!r}, "
            f"the content hashes to {actual!r}. Regenerate it, never edit it."
        )
    return payload


@lru_cache(maxsize=1)
def load_criteria() -> CriteriaCache:
    """The committed EU criterion list. No network, no mutation -- the model is frozen."""
    try:
        return CriteriaCache.model_validate(_read_cache(criteria_path()))
    except ValidationError as err:
        message = f"{criteria_path()} does not match CriteriaCache: {err}"
        raise EcertisCacheError(message) from err


@lru_cache(maxsize=8)
def _load_evidence_file(country: str) -> EvidenceCache:
    """Memoised on an already-normalised code. Call `load_evidence`, not this."""
    path = evidence_path(country)
    try:
        return EvidenceCache.model_validate(_read_cache(path))
    except ValidationError as err:
        raise EcertisCacheError(f"{path} does not match EvidenceCache: {err}") from err


def load_evidence(country: str) -> EvidenceCache:
    """One country's committed evidence lists. Raises only if the file is absent or bad.

    The code is normalised *before* the memoised call, not inside it: `lru_cache` keys on
    the argument it was given, so lower-casing in the body would make `"DE"` and `"de"`
    two entries and parse the same 300 kB file twice.
    """
    return _load_evidence_file(country.lower())


@lru_cache(maxsize=8)
def _evidence_index(country: str) -> Mapping[str, CachedCriterionEvidence]:
    """Also memoised on an already-normalised code. Call `find_evidence`, not this."""
    rows = {row.criterion_id: row for row in _load_evidence_file(country).criteria}
    return MappingProxyType(rows)


def find_evidence(criterion_id: str, country: str) -> CachedCriterionEvidence | None:
    """The country's proof for one EU criterion.

    `None` means the criterion id is not in the cache at all -- S1.1.2's `not_found`. A
    criterion that exists but has no national evidence comes back with empty
    `sub_criteria`, because "this country files no paper for that" is an answer, not a
    failure.
    """
    return _evidence_index(country.lower()).get(criterion_id)


def clear_caches() -> None:
    """Drop the memoised files. Only the build script needs this, after it rewrites them."""
    load_criteria.cache_clear()
    _load_evidence_file.cache_clear()
    _evidence_index.cache_clear()
